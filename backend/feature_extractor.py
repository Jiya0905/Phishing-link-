"""
feature_extractor.py
---------------------
This file converts a raw URL (just text, like "http://paypal-verify-login.com")
into a set of NUMBERS that a Machine Learning model can understand.

WHY DO WE NEED THIS?
Machine Learning models cannot read text/URLs directly. They only understand
numbers. So we look at the URL and count/measure things that are typically
different between a SAFE url and a PHISHING url. This is called
"Feature Engineering".

Every function below measures one property of the URL.
"""

import re
import math
from urllib.parse import urlparse

# A short list of words that phishing URLs commonly use to trick users
SUSPICIOUS_WORDS = [
    "login", "verify", "account", "update", "secure", "bank", "confirm",
    "signin", "sign-in", "password", "pay", "wallet", "gift", "bonus",
    "free", "click", "urgent", "suspend", "limited", "webscr", "ebayisapi",
    "recover", "unlock", "security", "alert"
]

# Common services people use to shorten/hide a real URL
SHORTENING_SERVICES = [
    "bit.ly", "goo.gl", "tinyurl.com", "ow.ly", "t.co", "is.gd",
    "buff.ly", "adf.ly", "shorte.st", "cutt.ly"
]


def has_ip_address(domain: str) -> int:
    """Phishing sites often use a raw IP address instead of a real domain name."""
    ip_pattern = r"^(\d{1,3}\.){3}\d{1,3}$"
    return 1 if re.match(ip_pattern, domain) else 0


def shannon_entropy(text: str) -> float:
    """
    Entropy measures how 'random' the text looks.
    Random-looking domains (auto-generated by attackers) have HIGH entropy.
    """
    if not text:
        return 0.0
    freq = {}
    for ch in text:
        freq[ch] = freq.get(ch, 0) + 1
    entropy = 0.0
    length = len(text)
    for count in freq.values():
        p = count / length
        entropy -= p * math.log2(p)
    return round(entropy, 3)


def _normalize_url(url: str) -> str:
    url = url.strip()
    if not url.startswith("http://") and not url.startswith("https://"):
        url = "http://" + url  # so urlparse can read it correctly
    return url


def get_matched_suspicious_words(url: str) -> list:
    """
    Returns the ACTUAL suspicious keyword(s) found in this specific URL
    (e.g. ["verify", "login"]), instead of just a count. Used by explain.py
    so the "why" reasons name the real matched words, not a fixed example
    list.
    """
    full_url = _normalize_url(url).lower()
    return [w for w in SUSPICIOUS_WORDS if w in full_url]


def extract_features(url: str) -> dict:
    """
    MAIN FUNCTION.
    Takes a URL string, returns a dictionary of numeric features.
    """
    url = _normalize_url(url)

    parsed = urlparse(url)
    domain = parsed.netloc.lower()
    path = parsed.path.lower()
    full_url = url.lower()

    features = {
        "url_length": len(url),
        "domain_length": len(domain),
        "num_dots": url.count("."),
        "num_hyphens": url.count("-"),
        "num_underscores": url.count("_"),
        "num_slashes": url.count("/"),
        "num_digits": sum(c.isdigit() for c in url),
        "num_at_symbols": url.count("@"),
        "num_equals": url.count("="),
        "num_ampersands": url.count("&"),
        "num_percent": url.count("%"),
        "num_question_marks": url.count("?"),
        "has_ip_address": has_ip_address(domain.split(":")[0]),
        "has_https": 1 if url.startswith("https://") else 0,
        "num_subdomains": max(domain.count(".") - 1, 0),
        "has_suspicious_word": 1 if any(w in full_url for w in SUSPICIOUS_WORDS) else 0,
        "suspicious_word_count": sum(1 for w in SUSPICIOUS_WORDS if w in full_url),
        "is_shortened": 1 if any(s in domain for s in SHORTENING_SERVICES) else 0,
        "has_double_slash_redirect": 1 if "//" in path else 0,
        "domain_entropy": shannon_entropy(domain),
        "digit_letter_ratio": round(
            sum(c.isdigit() for c in domain) / (len(domain) + 1), 3
        ),
    }
    return features


# Fixed order of feature names -> IMPORTANT: model must always see features
# in this exact order, both while training and while predicting.
FEATURE_NAMES = list(extract_features("http://example.com").keys())


